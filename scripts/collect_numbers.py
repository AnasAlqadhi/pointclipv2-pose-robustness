"""Regenerate docs/NUMBERS.md: every reportable number, straight from the result files.

Verifying the report then means comparing it against a machine-generated table
instead of hunting through JSON. If a number is in the report and not here, it
either came from somewhere else - say where - or it should not be there.

Usage:
    python scripts/collect_numbers.py
"""

from __future__ import annotations

import datetime
import glob
import json
import os

RESULTS = "results"
OUT = "docs/NUMBERS.md"


def load(name):
    p = os.path.join(RESULTS, f"{name}.json")
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def pct(acc):
    return f"{100 * acc['value']:.2f}% [{100 * acc['lo']:.2f}, {100 * acc['hi']:.2f}]"


def main():
    lines = [
        "# Every reportable number, generated from the result files",
        "",
        f"Generated by `scripts/collect_numbers.py` on {datetime.date.today().isoformat()}. "
        "**Do not edit by hand** - re-run the script.",
        "",
        "Use this to check the report: every figure in section 7 should appear here, with the same value. "
        "A number in the report that is not here needs its source named or removed.",
        "",
    ]

    # --- single evaluations -------------------------------------------------
    lines += ["## Single evaluations", "", "| run | n | overall | macro | source file |", "|---|---|---|---|---|"]
    for path in sorted(glob.glob(os.path.join(RESULTS, "*.json"))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path) as f:
            r = json.load(f)
        if "accuracy" not in r or "rows" in r or "angles" in r:
            continue
        flag = " **(smoke test - not reportable)**" if r.get("limit") else ""
        lines.append(
            f"| `{name}`{flag} | {r['n_objects']} | {pct(r['accuracy'])} | "
            f"{100 * r['macro_accuracy']:.2f}% | `results/{name}.json` |"
        )

    # --- sweeps -------------------------------------------------------------
    lines += ["", "## Yaw sweeps", "", "| run | angles | at 0 deg | best | worst | spread |", "|---|---|---|---|---|---|"]
    for path in sorted(glob.glob(os.path.join(RESULTS, "yaw_sweep_*.json"))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path) as f:
            r = json.load(f)
        vals = [(a["angle_deg"], 100 * a["accuracy"]["value"]) for a in r["angles"]]
        zero = next(v for a, v in vals if a == 0)
        best = max(vals, key=lambda t: t[1])
        worst = min(vals, key=lambda t: t[1])
        lines.append(
            f"| `{name}` | {len(vals)} | {zero:.2f}% | {best[1]:.2f}% at {best[0]:.0f} deg | "
            f"{worst[1]:.2f}% at {worst[0]:.0f} deg | **{best[1] - worst[1]:.2f}** |"
        )

    # --- fix experiments ----------------------------------------------------
    for path in sorted(glob.glob(os.path.join(RESULTS, "fix_*.json"))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path) as f:
            r = json.load(f)
        if r.get("config", {}).get("limit"):
            continue
        lines += ["", f"## Fix conditions: `{name}`", "",
                  "| condition | " + " | ".join(f"{a['angle_deg']:.0f} deg" for a in
                                                [x for x in r["rows"] if x["condition"] == "baseline"]) +
                  " | mean | spread | CLIP passes |",
                  "|---" * (len([x for x in r["rows"] if x["condition"] == "baseline"]) + 4) + "|"]
        conds = []
        for row in r["rows"]:
            if row["condition"] not in conds:
                conds.append(row["condition"])
        for cond in conds:
            vals = [100 * x["accuracy"]["value"] for x in r["rows"] if x["condition"] == cond]
            passes = next(x["clip_passes_per_object"] for x in r["rows"] if x["condition"] == cond)
            lines.append(
                f"| {cond} | " + " | ".join(f"{v:.2f}" for v in vals) +
                f" | **{sum(vals) / len(vals):.2f}** | {max(vals) - min(vals):.2f} | {passes} |"
            )
        lines += ["", "Paired differences against baseline (same objects, same angle):", "",
                  "| condition | angle | delta (points) | 95% interval | verdict |", "|---|---|---|---|---|"]
        for d in r["paired_vs_baseline"]:
            dd = d["delta"]
            lines.append(
                f"| {d['condition']} | {d['angle_deg']:.0f} deg | {100 * dd['value']:+.2f} | "
                f"[{100 * dd['lo']:+.2f}, {100 * dd['hi']:+.2f}] | {d['verdict']} |"
            )

    # --- span sweep ---------------------------------------------------------
    span = load("span_sweep_modelnet40")
    if span:
        lines += ["", "## Ensemble span sweep", "", "| span | angle | accuracy | delta vs baseline | verdict |",
                  "|---|---|---|---|---|"]
        for row in span["rows"]:
            if row["span_deg"] is None:
                lines.append(f"| baseline | {row['angle_deg']:.0f} deg | {pct(row['accuracy'])} | - | - |")
            else:
                d = row["delta"]
                lines.append(
                    f"| {row['span_deg']:.2f} deg | {row['angle_deg']:.0f} deg | {pct(row['accuracy'])} | "
                    f"{100 * d['value']:+.2f} [{100 * d['lo']:+.2f}, {100 * d['hi']:+.2f}] | {row['verdict']} |"
                )

    # --- search replication -------------------------------------------------
    reps = sorted(glob.glob(os.path.join(RESULTS, "search_replication_*.json")))
    if reps:
        lines += ["", "## Replication of the upstream evaluation-time prompt search",
                  "", "**These runs tune on the test labels on purpose, to measure the upstream procedure. "
                      "No number here is an accuracy our method achieves.**", "",
                  "| backbone | shipped start | after search | gain | prompts replaced |", "|---|---|---|---|---|"]
        for path in reps:
            with open(path) as f:
                r = json.load(f)
            lines.append(
                f"| {r['backbone']} | {100 * r['shipped_accuracy']:.2f}% | "
                f"**{100 * r['searched_accuracy']:.2f}%** | +{r['gain_points']:.2f} | "
                f"{r['prompts_replaced']} of 40 |"
            )

    lines += ["", "## Published figures (the paper's, never ours)", "",
              "| source | ModelNet40 | ScanObjectNN |", "|---|---|---|",
              "| paper, as commonly quoted | 64.22 | - |",
              "| upstream README, ViT-B/16 | 64.26 | 35.66 |",
              "| upstream README, ViT-B/32 | 55.14 | 36.36 |",
              "| upstream README, RN101 | 46.31 | 29.84 |",
              "| upstream README, RN50 | 39.38 | 35.32 |", "",
              "Split-level ScanObjectNN numbers (OBJ_BG 41.22, OBJ_ONLY 50.09, PB_T50_RS 35.36) come from "
              "secondary sources that disagree with each other and are **unverified** - check the paper's "
              "own table before citing them.", ""]

    os.makedirs("docs", exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
